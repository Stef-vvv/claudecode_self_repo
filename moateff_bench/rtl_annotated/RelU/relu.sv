// ============================================================================
// 模块名称: relu (ReLU激活函数单元)
// 在架构中的位置: ReLU - 激活函数计算模块
//
// 功能描述:
//   实现ReLU (Rectified Linear Unit) 激活函数:
//   out = max(0, in)
//
//   对于有符号2's补码数:
//   - 如果MSB(符号位)为0: 正数或零，out = in (直通)
//   - 如果MSB(符号位)为1: 负数，out = 0 (全部清零)
//
//   纯组合逻辑，零周期延迟。
//
// 数据格式:
//   - DATA_WIDTH位有符号2's补码（默认为16位Q0.8定点数）
//   - 符号位 = in[DATA_WIDTH-1]
//
// 注意:
//   不适用于浮点数。仅适用于有符号整数/定点数的符号位检测。
// ============================================================================

module relu
#(
    parameter DATA_WIDTH = 16          // 数据位宽（默认16位，Q0.8有符号定点数）
)(
    input  [DATA_WIDTH - 1:0] in,     // 输入数据（有符号2's补码）
    output [DATA_WIDTH - 1:0] out     // 输出数据: out = (in >= 0) ? in : 0
);

    // ========================================================================
    // ReLU函数: 符号位检测
    // in[DATA_WIDTH-1] = 1'b0: 非负数，输出等于输入
    // in[DATA_WIDTH-1] = 1'b1: 负数，输出全零
    // {DATA_WIDTH{1'b0}} 生成宽度匹配的零向量
    // ========================================================================
    assign out = (in[DATA_WIDTH - 1] == 1'b0) ? in : {DATA_WIDTH{1'b0}};

endmodule
