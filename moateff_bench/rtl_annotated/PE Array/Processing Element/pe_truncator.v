// ============================================================================
// 模块名称: truncator (截断器 / 位选择器)
// 架构位置: pe.v 内部的截断器子模块 (MAC流水第2级)
//           pe(PE核心) -> multiplier -> truncator(本模块) -> adder
//
// 模块功能: 从 32-bit 乘法结果中截取连续的 16-bit 作为输出
//           sel 参数选择起始位: out[i] = in[sel + i], i = 0..15
//           将 Q0.16 格式 (32-bit) 截断为 Q0.8 格式 (16-bit)
//
// 截断说明 (sel=0 时):
//   32-bit Q0.16: [符号|整数14:0|小数15:0]
//   取低16位得到 Q0.8: [符号|整数6:0|小数7:0]
//   Q0.8 * Q0.8 = Q0.16 (32-bit), 截取低16位即为所需Q0.8精度
//   高位主要是符号扩展位, 只要计算不溢出16位范围即可安全截断
// ============================================================================
module truncator
#(
    parameter DATA_WIDTH = 16,                // 输出数据宽度 (默认16)
    parameter SEL_WIDTH  = $clog2(DATA_WIDTH) // sel信号位宽 = clog2(16) = 4
)(
    input  wire [(2 * DATA_WIDTH) - 1:0] in,   // 输入: 32-bit 乘法结果 (Q0.16)
    input  wire [SEL_WIDTH:0]            sel,  // 选择位: 起始位索引 (5-bit, 默认0)
    output reg  [DATA_WIDTH-1:0]         out   // 输出: 截断后的 16-bit 数据
);

    integer i;
    // =======================================================================
    // 截断逻辑: 组合电路
    // always @(in or sel): 输入或sel变化时立即更新
    // for 循环: out[i] = in[sel + i], i = 0..15
    // 例: sel=0  -> out = in[15:0] (取低16位)
    //     sel=5  -> out = in[20:5] (从第5位开始取16位)
    // =======================================================================
    always @(in or sel) begin
        for (i = 0; i < DATA_WIDTH; i = i + 1) begin
            out[i] = in[sel + i];  // 逐位选择: 第i个输出位 = 第(sel+i)个输入位
        end
    end

endmodule
