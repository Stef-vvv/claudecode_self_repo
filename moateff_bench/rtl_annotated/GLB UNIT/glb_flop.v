// ============================================================================
// 模块名称: flop (GLB流水线寄存器 / D触发器)
// 在架构中的位置: GLB UNIT - 基础时序单元
//
// 功能描述:
//   参数化的单级D触发器（Flip-Flop），用于GLB内部地址总线的流水线对齐。
//   在ifmap_glb/filter_glb/bias_glb/psum_glb中用于延迟端口B的读地址，
//   以匹配BRAM读延迟（BRAM输出在下一周期才有效），确保读数据与地址对齐。
//
// 时钟域说明:
//   - negege（下降沿）触发，与dual_bram保持一致
//   - 本模块只在glb_unit内部使用，与core_clk同步
// ============================================================================

module flop
#(
    parameter DATA_WIDTH = 16      // 数据位宽，由上层调用者指定（通常为地址宽度ADDR_WIDTH）
)(
    input wire clk,                // 时钟信号（negedge下降沿触发）
    input wire [DATA_WIDTH-1:0] d, // 输入数据（D端）
    output reg [DATA_WIDTH-1:0] q  // 输出数据（Q端），延迟一个周期
);

    // ========================================================================
    // 单周期延迟: 下降沿寄存输入到输出
    // q(n+1) = d(n)   （在negedge边沿更新）
    // 用途: 流水线中延迟地址信号，使地址与BRAM的读数据对齐
    // ========================================================================
    always @(negedge clk) begin
        q <= d;
    end

endmodule
